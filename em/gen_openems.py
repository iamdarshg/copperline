#!/usr/bin/env python3
"""Copperline openEMS project generator — full-wave RF validation.

Generates a complete openEMS FDTD simulation for each RF net of a
copperline routed board: build a microstrip model with the routed
geometry, add lumped ports, run the FDTD simulation and extract S11/S21
over a frequency sweep.

openEMS is NOT bundled here (it is GPL-3; copperline must stay
dependency-free and clean-room).  This generator only *writes* a
self-contained simulation script that runs against a user-installed
openEMS (pip install openEMS, or the Octave distribution).  The script
is generated from scratch — no openEMS source is embedded or copied.

Usage:
    python gen_openems.py <board.json> [--config config.json] [--out dir]

Produces, per RF net with a target:
    <out>/<net>_sim.py      openEMS driver (run with: python <net>_sim.py)
    <out>/<net>_model.xml   CSXCAD structure (written by the driver)

The driver needs `import openEMS` to succeed; if that import fails the
driver exits with a clear message instead of crashing.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import rf_models as rf
import validate_rf as vrf

DRIVER_TEMPLATE_HEADER = """\
#!/usr/bin/env python3
\"\"\"openEMS FDTD simulation for copperline routed net {net!r} (net id {net_id}).

Generated by copperline em/gen_openems.py -- clean-room generation,
no openEMS source is embedded.  Requires openEMS >= 0.0.36:
    pip install openEMS   (or the Octave/conda distribution)

Model: {struct} trace, width {width} mm over {h} mm dielectric
(eps_r = {eps_r}, tan_d = {tan_d}), copper {oz} oz.

Run:
    python {net}_sim.py
\"\"\"

import os, math, tempfile

# --- geometry from the copperline routed board -------------------------------
W_MM = {width}
H_MM = {h}            # dielectric height
L_MM = {length}       # trace length
T_CU_MM = {t_cu}      # copper thickness
EPS_R = {eps_r}
TAN_D = {tan_d}
F_MIN_GHZ = {fmin}
F_MAX_GHZ = {fmax}

# --- openEMS import (fail with a clear message if absent) --------------------
try:
    from openEMS import openEMS
    from openEMS.ports import LumpedPort
    from CSXCAD import ContinuousStructure
except ImportError as _e:
    raise SystemExit(
        "openEMS not importable -- run `pip install openEMS` first. "
        f"(import error: {{_e}})")

def main():
    sim_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "simdata")
    os.makedirs(sim_dir, exist_ok=True)
    FDTD = openEMS(NrTS=0)
    csx = ContinuousStructure()
    FDTD.SetCSX(csx)

    # substrate block
    sub = csx.AddMaterial(name="FR4")
    sub.SetMaterialProperty("epsilon", EPS_R)
    sub.SetMaterialProperty("kappae", 0.0)
    sub.AddMaterialProperty("tau_eps", 0.0)
    sub.SetMaterialProperty("mue", 1.0)
    sub.SetMaterialProperty("sigmaTanD", TAN_D)
    substrate = sub.AddBox(
        start=[0, 0, -H_MM], stop=[W_MM + 4, L_MM + 4, 0], priority=0)

    # ground plane (bottom)
    ground = csx.AddMetal(name="GND")
    gp = ground.AddBox(
        start=[-1, -1, -H_MM - 1], stop=[W_MM + 5, L_MM + 5, -H_MM], priority=1)

    # trace (top)
    trace_metal = csx.AddMetal(name="strip")
    tp = trace_metal.AddBox(
        start=[0, 0, -T_CU_MM], stop=[W_MM, L_MM, 0], priority=2)

    # mesh
    FDTD.SetGroundedPlane(true_dir="-z")
    FDTD.Add2DGrid(dz=H_MM / 10.0)
    FDTD.SetBoundaryCond(["MUR", "MUR", "MUR", "MUR", "MUR", "MUR"])

    # ports at each end
    port_start = [0, 0, -H_MM]
    port_stop = [W_MM, 0, 0]
    port1 = LumpedPort(priority=10)
    port1.SetPortNumber(1)
    port1.SetDirection("x")
    port1.SetPortImp(1.0)
    port1.SetExcitedByPort(True)
    port1.SetBox(port_start, port_stop)
    port2 = LumpedPort(priority=10)
    port2.SetPortNumber(2)
    port2.SetDirection("x")
    port2.SetBox([0, L_MM, -H_MM], [W_MM, L_MM, 0])
    FDTD.AddPort(port1)
    FDTD.AddPort(port2)

    # frequency sweep + excitation
    f0 = (F_MIN_GHZ + F_MAX_GHZ) / 2.0
    f_units = 1e9
    FDTD.SetGaussianExcite(f0 * f_units, 0.4 * f0 * f_units)
    FDTD.SetDumpMode(0)
    FDTD.SetEndCriteria(1e-5)
    FDTD.Run(sim_dir, cleanup=False, verbose=2)

    # S-parameters
    import h5py
    sp = FDTD.GetSParameters()
    freq = sp.m_f / 1e9
    s11 = abs(sp.S[0, 0, :]) ** 2
    s21 = abs(sp.S[1, 0, :]) ** 2
    print("openEMS S-parameter results for net {net!r}:")
    for i, f in enumerate(freq):
        print(f"  f={{f:.3f}} GHz  |S11|={{10*math.log10(s11[i]) if s11[i]>0 else -300:.1f}} dB  "
              f"|S21|={{10*math.log10(s21[i]) if s21[i]>0 else -300:.1f}} dB")

if __name__ == "__main__":
    main()
"""


def generate_projects(board: dict, reports: list, cfg: dict,
                      out_dir: str) -> list[str]:
    """Write an openEMS driver per RF net that has a Z0 target."""
    os.makedirs(out_dir, exist_ok=True)
    stackup = cfg["stackup"]
    rfc = cfg["rf"]
    targets = rfc.get("targets", {})
    h = stackup.get("dielectric_mm", 1.6)
    eps_r = stackup.get("eps_r", 4.4)
    tan_d = stackup.get("tan_d", 0.02)
    oz = stackup.get("copper_weight_oz", 1.0)
    fmax = float(rfc.get("freq_ghz", 2.45))
    fmin = max(0.1, fmax / 10.0)

    written = []
    for r in reports:
        if r["structure"] == "unknown":
            continue
        name = r["net"]
        width = r["width_mm"]
        length = r["length_mm"]
        t_cu = rf.copper_thickness_mm(oz)
        driver = DRIVER_TEMPLATE_HEADER.format(
            net=name, net_id="-", struct=r["structure"], width=width,
            h=h, eps_r=eps_r, tan_d=tan_d, oz=oz, length=length,
            t_cu=t_cu, fmin=fmin, fmax=fmax)
        fname = os.path.join(out_dir, f"{name}_sim.py")
        with open(fname, "w", encoding="utf-8") as fh:
            fh.write(driver)
        written.append(fname)
    return written


def main() -> int:
    ap = argparse.ArgumentParser(description="Copperline openEMS generator")
    ap.add_argument("board", help="routed board JSON")
    ap.add_argument("--config", help="EM config JSON")
    ap.add_argument("--out", default="em_openems", help="output dir")
    args = ap.parse_args()

    with open(args.board, "r", encoding="utf-8") as fh:
        board = json.load(fh)
    cfg = vrf.load_config(args.config)
    vrf._BOARD = board
    traces_by_net = vrf.net_traces(board)
    reports = []
    for net in board.get("nets", []):
        traces = traces_by_net.get(net.get("id"), [])
        if traces:
            reports.append(vrf.evaluate_net(net, traces, cfg))
    written = generate_projects(board, reports, cfg, args.out)
    print(f"Generated {len(written)} openEMS driver(s) in {args.out}:")
    for w in written:
        print(f"  {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())